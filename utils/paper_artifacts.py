def build_per_corpus_ci(dataset_names: list[str]) -> str | None:
    header = ["Model", "\\texttt{MAP@10} [95\\% CI]",
              "Leader$-$model $\\Delta$ [95\\% CI]", "Sep."]
    rows: list[list[str]] = []
    groups: list[tuple[int, str]] = []
    for name in dataset_names:
        block = load_bootstrap(name)
        if block is None:
            return None
        leader = block["leader"]
        groups.append((len(rows),
                       f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{\\texttt{{{tex_escape_dataset(name)}}}}} "
                       f"($n={block['n_queries']}$ scored queries; leader \\texttt{{{leader}}})}} \\\\"))
        order = sorted(block["ci"], key=lambda k: -block["ci"][k]["map"]["mean"])
        for lab in order:
            m = block["ci"][lab]["map"]
            cell = f"{m['mean']:.3f} [{m['lo']:.3f}, {m['hi']:.3f}]"
            if lab == leader:
                rows.append([f"\\quad {lab}", cell, "---", "---"])
                continue
            p = block["paired_map_vs_leader"][lab]
            delta = (f"${p['delta']:+.3f}$ [${p['lo']:+.3f}$, ${p['hi']:+.3f}$]")
            rows.append([f"\\quad {lab}", cell, delta,
                         "yes" if bs.excludes_zero(p) else "\\textbf{no}"])
    return tabular("@{}lccc@{}", header, rows, group_rows=groups)


def build_pooled_ci(dataset_names: list[str]) -> str | None:
    try:
        pooled, _ = bs.pooled_over_datasets(dataset_names)
    except FileNotFoundError:
        return None
    leader = pooled["leader"]
    header = ["Model", "Mean \\texttt{MAP@10} [95\\% CI]",
              f"\\texttt{{{leader}}}$-$model $\\Delta$ [95\\% CI]"]
    order = sorted(pooled["ci_map"], key=lambda k: -pooled["ci_map"][k]["mean"])
    rows = []
    for lab in order:
        m = pooled["ci_map"][lab]
        cell = f"{m['mean']:.3f} [{m['lo']:.3f}, {m['hi']:.3f}]"
        if lab == leader:
            rows.append([lab, cell, "---"])
            continue
        p = pooled["paired_map_vs_leader"][lab]
        rows.append([lab, cell,
                     f"${p['delta']:+.3f}$ [${p['lo']:+.3f}$, ${p['hi']:+.3f}$]"])
    return tabular("@{}lcc@{}", header, rows)


