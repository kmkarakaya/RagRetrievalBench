"""Generate the manuscript's data tables as LaTeX fragments.

Every number the paper reports in a data table comes from a pipeline artifact:
`datasets/<name>/reports/raw_results_*.json`, `datasets/<name>/qrels.tsv`, and the
query-level uncertainty blocks written by `utils/bootstrap_utils.py`. Typing those
numbers by hand is the single largest source of silent error in the manuscript, so
they are emitted here instead.

Each fragment contains ONLY a `tabular` environment. The surrounding `table` float,
the `\\caption` and the `\\label` stay in the hand-authored section files, so wording
and placement remain editorial decisions while the numbers do not.

Fragments are written flat into `journal_paper/` as `tbl_<label>.tex`, because the
manuscript build (`journal_paper/build.ps1`) enforces flat sources: lint rule CAS301
rejects `\\input{subdir/file}` and only root-level `*.tex` is copied into the build
directory.

Usage:
    python utils/paper_artifacts.py                  # all datasets in config order
    python rag_benchmark.py --paper-tables           # same, via the pipeline CLI
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import config as cfg  # noqa: E402
from utils import bootstrap_utils as bs  # noqa: E402
from utils.generate_journal_results_figures import (  # noqa: E402
    build_alias_map,
    latency_ms,
    metric_value,
    ordered_aliases,
    query_count,
    weighted_latency_ms,
)

OUTPUT_DIR = PROJECT_ROOT / "journal_paper"

# Short family names used in the manuscript's cross-dataset table. Keyed by the
# tail of the sentence-transformers model id so a roster change fails loudly here
# rather than silently mislabelling a row.
FAMILY_NAMES = {
    "all-MiniLM-L6-v2": "MiniLM-L6",
    "all-mpnet-base-v2": "MPNet",
    "paraphrase-multilingual-MiniLM-L12-v2": "multi-MiniLM",
    "all-MiniLM-L12-v2": "MiniLM-L12",
    "paraphrase-multilingual-mpnet-base-v2": "multi-MPNet",
}

METRIC_COLUMNS = [
    ("map", "MAP@10", 4),
    ("recall", "Recall@10", 4),
    ("precision", "Precision@10", 3),
    ("ndcg", "NDCG@10", 4),
    ("mrr", "MRR@10", 4),
    ("hit_rate", "Success@10", 2),
]


# ----------------------------------------------------------------------------------
# helpers
# ----------------------------------------------------------------------------------

def tex_escape_dataset(name: str) -> str:
    return name.replace("_", r"\_")


def thousands(n: int) -> str:
    """LaTeX thousands separator as used throughout the manuscript."""
    s = f"{int(n):,}"
    return s.replace(",", "{,}")


def family_name(model_name: str) -> str:
    tail = model_name.split("/")[-1]
    if tail not in FAMILY_NAMES:
        raise KeyError(
            f"No short family name for {model_name!r}. Add it to FAMILY_NAMES in "
            f"utils/paper_artifacts.py so the manuscript table stays correctly labelled."
        )
    return FAMILY_NAMES[tail]


def stack(*lines: str, align: str = "r") -> str:
    """A column header broken over several lines.

    Long single-line headers push these tables past the journal's 372pt text
    block; stacking them keeps the full wording without the overflow.
    """
    return ("\\begin{tabular}[b]{@{}" + align + "@{}}"
            + r" \\ ".join(lines) + "\\end{tabular}")


def tabular(colspec: str, header: list[str], rows: list[list[str]],
            group_rows: list[tuple[int, str]] | None = None) -> str:
    """Render a booktabs tabular. group_rows inserts a full-width row before index i."""
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule",
             " & ".join(header) + r" \\", "\\midrule"]
    groups = dict(group_rows or [])
    for i, row in enumerate(rows):
        if i in groups:
            if i:
                lines.append(r"\addlinespace")
            lines.append(groups[i])
        lines.append(" & ".join(row) + r" \\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def write_fragment(label: str, body: str) -> Path:
    path = OUTPUT_DIR / f"tbl_{label}.tex"
    header = (
        "% Generated by utils/paper_artifacts.py from the pipeline's run artifacts.\n"
        "% Do not edit by hand: regenerate with `python rag_benchmark.py --paper-tables`.\n"
    )
    path.write_text(header + body, encoding="utf-8")
    return path


