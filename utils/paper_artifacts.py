def resolve_dataset_names(dataset_names: list[str] | None = None) -> list[str]:
    """Which datasets the manuscript artifacts are built from.

    An explicit argument wins; otherwise cfg.paper_datasets pins the set so that a
    scratch dataset left in datasets/ cannot leak into the paper; otherwise fall back
    to auto-discovery.
    """
    if dataset_names:
        return list(dataset_names)
    pinned = getattr(cfg, "paper_datasets", None)
    if pinned:
        available = set(cfg.discover_available_datasets())
        missing = [d for d in pinned if d not in available]
        if missing:
            raise FileNotFoundError(
                f"config.paper_datasets names {missing}, which are not present under "
                f"datasets/. Fix the list or evaluate those datasets first."
            )
        return list(pinned)
    return cfg.discover_available_datasets()


def generate(dataset_names: list[str] | None = None) -> list[Path]:
    dataset_names = resolve_dataset_names(dataset_names)
    datasets = load_dataset_artifacts(dataset_names)
    alias_map = build_alias_map(datasets[dataset_names[0]])

    written: list[Path] = []

    for name in dataset_names:
        written.append(write_fragment(f"{name}_metrics",
                                      build_dataset_metrics(name, datasets[name], alias_map)))
        written.append(write_fragment(f"{name}_timing",
                                      build_dataset_timing(name, datasets[name], alias_map)))

    written.append(write_fragment("dataset_statistics_summary",
                                  build_dataset_statistics(datasets, alias_map)))
    written.append(write_fragment("cross_dataset_consistency_summary",
                                  build_cross_dataset_consistency(datasets, alias_map)))
    written.append(write_fragment("quality_speed_summary",
                                  build_quality_speed(datasets, alias_map)))

    for label, ds_a, ds_b, arrow, with_family in getattr(cfg, "paper_comparisons", []):
        if ds_a in datasets and ds_b in datasets:
            written.append(write_fragment(
                label, build_pair_comparison(datasets, alias_map, ds_a, ds_b,
                                             arrow, with_family)))

    per_corpus = build_per_corpus_ci(dataset_names)
    if per_corpus:
        written.append(write_fragment("per_corpus_ci", per_corpus))
    pooled = build_pooled_ci(dataset_names)
    if pooled:
        written.append(write_fragment("bootstrap_ci", pooled))
    if not per_corpus or not pooled:
        print("[Skip] uncertainty tables: run the bootstrap stage first "
              "(python rag_benchmark.py --bootstrap --dataset <name>)")

    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--datasets", type=str, default=None,
                    help="Comma-separated dataset names. Default: all discovered.")
    args = ap.parse_args()
    names = [d.strip() for d in args.datasets.split(",")] if args.datasets else None
    written = generate(names)
    print(f"Wrote {len(written)} LaTeX table fragments to {OUTPUT_DIR}:")
    for p in written:
        print(f"  {p.name}")


if __name__ == "__main__":
    main()
