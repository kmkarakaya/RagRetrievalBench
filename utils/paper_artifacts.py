def build_dataset_statistics(datasets: dict, alias_map: dict) -> str:
    header = ["Dataset", stack("Source", "documents"), "Chunks",
              stack("Generated", "queries"), stack("Scored", "queries"),
              stack("Judged", "pairs"), stack("Positive", "qrels")]
    rows = []
    totals = [0] * 6
    for name, data in datasets.items():
        stats = data["corpus_stats"]
        any_model = next(iter(alias_map))
        scored = query_count(data, any_model)
        judged, positives = qrels_counts(name)
        vals = [int(stats["total_pdfs"]), int(stats["total_chunks"]),
                int(stats["total_queries"]), int(scored), judged, positives]
        totals = [t + v for t, v in zip(totals, vals)]
        rows.append([tex_escape_dataset(name)] + [thousands(v) for v in vals])
    rows.append(["Total"] + [thousands(v) for v in totals])
    return tabular("@{}l" + "r" * 6 + "@{}", header, rows)


def _macro_map(datasets: dict, model_name: str) -> float:
    return sum(metric_value(d, model_name, "map") for d in datasets.values()) / len(datasets)


def _ranks(datasets: dict, alias_map: dict) -> dict[str, float]:
    """Average rank by MAP@10 within each dataset (1 = best); ties share the mean rank."""
    totals = {m: 0.0 for m in alias_map}
    for data in datasets.values():
        scored = sorted(alias_map, key=lambda m: -metric_value(data, m, "map"))
        values = [metric_value(data, m, "map") for m in scored]
        for i, m in enumerate(scored):
            tied = [j for j, v in enumerate(values) if v == values[i]]
            totals[m] += (sum(tied) / len(tied)) + 1
    return {m: totals[m] / len(datasets) for m in alias_map}


def _wins(datasets: dict, alias_map: dict) -> dict[str, int]:
    wins = {m: 0 for m in alias_map}
    for data in datasets.values():
        best = max(alias_map, key=lambda m: metric_value(data, m, "map"))
        wins[best] += 1
    return wins


def build_cross_dataset_consistency(datasets: dict, alias_map: dict) -> str:
    header = ["Model", "Avg Rank", "Mean MAP@10 (across corpora)", "Wins"]
    ranks, wins = _ranks(datasets, alias_map), _wins(datasets, alias_map)
    ordered = sorted(alias_map, key=lambda m: -_macro_map(datasets, m))
    rows = [[f"{alias_map[m]} ({family_name(m)})",
             f"{ranks[m]:.2f}",
             f"{_macro_map(datasets, m):.4f}",
             str(wins[m])] for m in ordered]
    return tabular("@{}lrrr@{}", header, rows)


def build_quality_speed(datasets: dict, alias_map: dict) -> str:
    header = ["Model", stack("Mean", "MAP@10"), stack("Avg", "Rank"),
              stack("Weighted latency", "(ms/query)"),
              stack("Throughput range", "(chunks/s)")]
    names = list(datasets)
    ranks = _ranks(datasets, alias_map)
    rows = []
    for model_name, alias in ordered_aliases(alias_map):
        tputs = [float(datasets[n]["models"][model_name]["timing"]["chunks_per_second"])
                 for n in names]
        rows.append([
            alias,
            f"{_macro_map(datasets, model_name):.4f}",
            f"{ranks[model_name]:.2f}",
            f"{weighted_latency_ms(datasets, names, model_name):.2f}",
            f"{min(tputs):.1f}--{max(tputs):.1f}",
        ])
    return tabular("@{}lrrrr@{}", header, rows)


def build_pair_comparison(datasets: dict, alias_map: dict, ds_a: str, ds_b: str,
                          arrow: str, with_family: bool) -> str:
    """MAP@10 for two corpora side by side, plus the signed difference b - a."""
    a_lab, b_lab = tex_escape_dataset(ds_a), tex_escape_dataset(ds_b)
    header = ["Model"]
    if with_family:
        header.append("Family")
    header += [stack(a_lab, "MAP@10", align="c"),
               stack(b_lab, "MAP@10", align="c"),
               f"$\\Delta$ ({arrow})"]
    rows = []
    for model_name, alias in ordered_aliases(alias_map):
        # Round first, then subtract, so the delta a reader computes from the two
        # printed columns is exactly the delta printed in the third.
        va = round(metric_value(datasets[ds_a], model_name, "map"), 4)
        vb = round(metric_value(datasets[ds_b], model_name, "map"), 4)
        row = [alias]
        if with_family:
            fam = ("English-oriented"
                   if "multilingual" not in model_name else "Multilingual")
            row.append(fam)
        row += [f"{va:.4f}", f"{vb:.4f}", f"${vb - va:+.4f}$"]
        rows.append(row)
    colspec = "@{}l" + ("l" if with_family else "") + "ccr@{}"
    return tabular(colspec, header, rows)


