def load_dataset_artifacts(dataset_names: list[str]) -> dict[str, dict[str, Any]]:
    out = {}
    for name in dataset_names:
        path = cfg.get_latest_raw_results(name)
        if path is None:
            raise FileNotFoundError(
                f"No raw_results_*.json for {name}. Run the evaluation stage first."
            )
        with open(path, "r", encoding="utf-8") as f:
            out[name] = json.load(f)
    return out


def qrels_counts(dataset: str) -> tuple[int, int]:
    """(judged pairs, positive qrels) from the dataset's qrels.tsv.

    Judged pairs counts every query-chunk pair submitted to the LLM judge; the
    positives are the subset labelled relevant. Negatives are retained as 0-rows.
    """
    cfg.configure_for_dataset(dataset)
    judged = positives = 0
    with open(cfg.qrels_file, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split("\t")
            if len(parts) < 3:
                continue
            judged += 1
            if parts[2].strip() == "1":
                positives += 1
    return judged, positives


def load_bootstrap(dataset: str, variant: str = "frozen") -> dict[str, Any] | None:
    path = bs.bootstrap_output_path(dataset, variant)
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


