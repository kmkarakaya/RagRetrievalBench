def build_dataset_metrics(dataset: str, data: dict, alias_map: dict) -> str:
    # Success@10 carries a footnote marker only where every model rounds to the same
    # value, which is the case the footnote exists to explain.
    hit_rates = {round(metric_value(data, m, "hit_rate"), 2) for m in alias_map}
    tied = len(hit_rates) == 1

    header = ["Model"]
    for key, title, _ in METRIC_COLUMNS:
        if key == "hit_rate" and tied:
            title += "\\textsuperscript{a}"
        header.append(title)

    rows = []
    for model_name, alias in ordered_aliases(alias_map):
        row = [alias]
        for key, _, places in METRIC_COLUMNS:
            row.append(f"{metric_value(data, model_name, key):.{places}f}")
        rows.append(row)
    return tabular("@{}l" + "r" * len(METRIC_COLUMNS) + "@{}", header, rows)


def build_dataset_timing(dataset: str, data: dict, alias_map: dict) -> str:
    header = ["Model", "Chunks/s", "Avg ms/chunk", "Query latency (ms/query)"]
    rows = []
    for model_name, alias in ordered_aliases(alias_map):
        timing = data["models"][model_name]["timing"]
        rows.append([
            alias,
            f"{float(timing['chunks_per_second']):.1f}",
            f"{float(timing['avg_time_per_chunk']) * 1000.0:.2f}",
            f"{latency_ms(data, model_name):.2f}",
        ])
    return tabular("@{}lrrr@{}", header, rows)


